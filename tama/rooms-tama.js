// 法政大学 多摩キャンパスの教室の一覧。tama/index.html が読み込み、時間割と「いまどこ」の教室の欄の候補に出す。
// 2026-10-24 あおの依頼「時間割の教室名も予測変換的な機能があるとよいかも、法政からしらべて追加して 例）社会A301、B301」で作った。
// 出どころ：法政大学 教室設備ガイド（https://www.hoseikyoiku.jp/facilities/ の多摩キャンパスの各棟のページと、社会学部棟・経済学部棟の校舎案内図）。
// 書き方：社会学部A棟（4号館・高い棟）＝社会A301、社会学部B棟（5号館・低い棟）＝社会B201、大教室B棟（7号館）＝B301。
//   経済学部棟は 9号館（経済学部B棟）＝経済B111、10号館（経済学部C棟・大教室棟）＝経済C101 と、社会学部と同じ決まりで付けた（学生の書き方が分かったら直す）。
// 1件は [候補に出て入る名前, 別の呼び方…]。別の呼び方（号館・略した名前・読み）で打っても当たる。ほかのキャンパス・大学は、同じ形の別のファイルを作る。
const CAMPUS_ROOMS=(()=>{
  const out=[];
  // 名前の頭（prefix）と別の呼び方の頭（alias）を付けて、教室の番号をまとめて足す
  const add=(prefix,aliases,nums)=>nums.forEach(n=>out.push([prefix+n].concat(aliases.map(a=>a+n))));
  const range=(a,b)=>Array.from({length:b-a+1},(_,i)=>String(a+i));
  // 社会学部A棟（4号館）：3階 301〜306、4階 401〜408、5階 501〜504・515〜520、6階 611〜622（ゼミ室）、7階 711〜722（ゼミ室）
  add('社会A',['社A','社会学部A棟','4号館','しゃかいA'],[].concat(range(301,306),range(401,408),range(501,504),range(515,520),range(611,622),range(711,722)));
  out.push(['社会A 多目的ゼミ室','多目的ゼミ室','社会学部A棟 多目的ゼミ室']);
  // 社会学部B棟（5号館・低層棟）：1階 102〜106、2階 201〜203
  add('社会B',['社B','社会学部B棟','5号館','しゃかいB'],[].concat(range(102,106),range(201,203)));
  out.push(['メディア表現実習室','社会101','社会学部棟 メディア表現実習室']);
  // 大教室B棟（7号館）：B201・B202・B301
  add('B',['大教室B','大教室B棟','7号館'],['201','202','301']);
  // 大教室A棟（2号館）：ホール1つ
  out.push(['大教室A棟','大教室A棟ホール','Aホール','2号館','だいきょうしつA']);
  // 総合棟（1号館）
  ['CALL教室A','CALL教室B','CALL教室C','情報実習室1','情報実習室2','情報実習室3','遠隔講義室'].forEach(r=>out.push(['総合棟 '+r,r,'1号館 '+r,'そうごうとう '+r]));
  // 経済学部B棟（9号館・ゼミ棟）：1階 111〜117・120〜129、2階 211〜217・220〜224、3階 311〜317・320〜329
  add('経済B',['経B','経済学部B棟','9号館','けいざいB'],[].concat(range(111,117),range(120,129),range(211,217),range(220,224),range(311,317),range(320,329)));
  // 経済学部C棟（10号館・大教室棟）：101〜103・201〜203
  add('経済C',['経C','経済学部C棟','10号館','けいざいC'],['101','102','103','201','202','203']);
  // 11号館（経済学部棟の情報カフェテリアの上）：204〜206、304〜307
  add('11号館',['経済'],['204','205','206','304','305','306','307']);
  // 現代福祉学部棟（17号館）：201〜204・211〜217・301・302
  add('福祉',['現福','現代福祉','現代福祉学部棟','17号館','ふくし'],[].concat(range(201,204),range(211,217),['301','302']));
  ['コンピュータ実習室','心理学実験室','実習指導室'].forEach(r=>out.push(['福祉 '+r,r,'現福 '+r,'17号館 '+r]));
  // スポーツ健康学部棟（18号館）：1階 102〜108、2階 201〜207、3階 301〜307、4階 401〜405、5階 501
  add('スポ健',['スポーツ健康','スポーツ健康学部棟','18号館','すぽけん'],[].concat(['102','103','105','106','107','108'],range(201,207),range(301,307),range(401,405),['501']));
  // 研究・実験棟（12号館）：101・201・301・401
  add('研究実験棟',['研究・実験棟','12号館'],['101','201','301','401']);
  return out;
})();
