-- ---------------------------------------------------------------------------
-- 7. RLS を作り直す（前のポリシーはダッシュボードで作られた名前が分からないので、3つの表の分を全部消してから作る）
-- ---------------------------------------------------------------------------
do $$
declare p record;
begin
  for p in select policyname, tablename from pg_policies
            where schemaname = 'public' and tablename in ('tama_rooms', 'tama_room_members', 'tama_room_messages') loop
    execute format('drop policy %I on public.%I', p.policyname, p.tablename);
  end loop;
end $$;
alter table public.tama_rooms         enable row level security;
alter table public.tama_room_members  enable row level security;
alter table public.tama_room_messages enable row level security;

-- 部屋の情報（名前・ルールなど）はだれでも読める。作る・変える・消すは関数から（ポリシーを作らない）。招待コードは別の表
create policy "read rooms" on public.tama_rooms for select to authenticated using (true);

-- だれが入っているかは、同じ部屋の人だけ読める（悩みの部屋などで、参加していることが外に分からないように）
create policy "members read members" on public.tama_room_members for select to authenticated
  using (user_id = auth.uid() or public.tama_room_is_member(room_id::text));
-- 既読の時刻と通知のオフだけ自分で変えられる（参加は関数から。部屋を書き換えて入れないよう、列も絞る）
create policy "update own membership" on public.tama_room_members for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());
revoke update on public.tama_room_members from authenticated;
grant update (last_read_at, muted) on public.tama_room_members to authenticated;
create policy "leave as self" on public.tama_room_members for delete to authenticated
  using (user_id = auth.uid());

-- 投稿は参加している人だけ読める・書ける（消すのは関数から）
create policy "members read messages" on public.tama_room_messages for select to authenticated
  using (public.tama_room_is_member(room_id::text));
create policy "members post" on public.tama_room_messages for insert to authenticated
  with check (from_id::text = auth.uid()::text and public.tama_room_is_member(room_id::text));

notify pgrst, 'reload schema';

-- 確認：1つめは関数が14行、2つめはポリシーが tama_room_members=3・tama_room_messages=2・tama_rooms=1
select proname from pg_proc
 where proname in ('tama_room_list', 'tama_room_create', 'tama_room_join', 'tama_room_join_code', 'tama_room_update', 'tama_room_code',
                   'tama_room_kick', 'tama_room_delete_msg', 'tama_room_transfer', 'tama_room_close', 'tama_room_rsvp_set',
                   'tama_room_forget_me', 'tama_room_cleanup', 'tama_room_fits')
 order by proname;
select tablename, count(*) as ポリシー数 from pg_policies
 where schemaname = 'public' and tablename in ('tama_rooms', 'tama_room_members', 'tama_room_messages')
 group by tablename order by tablename;
